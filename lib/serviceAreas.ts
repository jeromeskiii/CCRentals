// Build a flat lookup map for fast ZIP code checking
const zipCodeMap = new Map<string, ServiceRegion>();

SERVICE_REGIONS.forEach((region) => {
  region.zips.forEach((zip) => {
    zipCodeMap.set(zip, region);
  });
});

// Check if a ZIP code is in our service area
export function isZipCodeServed(zipCode: string): { served: boolean; region?: ServiceRegion } {
  const normalizedZip = zipCode.replace(/\D/g, '').slice(0, 5);
  const region = zipCodeMap.get(normalizedZip);

  if (region) {
    return { served: true, region };
  }

  return { served: false };
}

// Get all served ZIP codes
export function getAllServedZipCodes(): string[] {
  return Array.from(zipCodeMap.keys());
}

// Get service regions as options for dropdown
export function getServiceRegionOptions(): { value: string; label: string; description: string }[] {
  return SERVICE_REGIONS.map((region) => ({
    value: region.name,
    label: region.name,
    description: region.description,
  }));
}

// Calculate distance from base (simplified - use a real geocoding service for accuracy)
export function estimateDistanceFromBase(zipCode: string): number | null {
  const normalizedZip = zipCode.replace(/\D/g, '').slice(0, 5);
  const region = zipCodeMap.get(normalizedZip);

  if (!region) return null;

  // Very rough estimate based on region - in production, use actual geocoding
  switch (region.name) {
    case 'Los Angeles County':
      return Math.floor(Math.random() * 30) + 5; // 5-35 miles
    case 'Orange County':
      return Math.floor(Math.random() * 30) + 30; // 30-60 miles
    case 'Ventura County':
      return Math.floor(Math.random() * 25) + 40; // 40-65 miles
    case 'San Bernardino County':
      return Math.floor(Math.random() * 40) + 50; // 50-90 miles
    case 'Riverside County':
      return Math.floor(Math.random() * 40) + 60; // 60-100 miles
    case 'San Diego County':
      return Math.floor(Math.random() * 30) + 100; // 100-130 miles
    default:
      return null;
  }
}
